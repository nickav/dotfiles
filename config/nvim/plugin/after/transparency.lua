-- Make highlight groups transparent while preserving their other attributes.
-- Skipped entirely under Neovide: this relies on a host terminal's own
-- background showing through once bg is stripped, but Neovide is a
-- standalone GUI window with no terminal behind it, so stripping bg there
-- just exposes Neovide's own hard-coded black fallback instead of the
-- colorscheme's actual background.
if vim.g.neovide then
  return
end

local function make_transparent(name)
	local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = name, link = false })
	if ok then
		hl.bg = nil
		vim.api.nvim_set_hl(0, name, hl)
	end
end

